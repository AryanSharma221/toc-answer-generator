import unittest
from core.universal_generator import solve_universal

class TestModeBCFGScenarios(unittest.TestCase):
    def setUp(self):
        self.grammar = "S -> aSb | epsilon"
        self.start_symbol = "S"

    def run_cfg(self, string):
        # We need to split strings like "aaabbb" into tokens ['a', 'a', 'a', 'b', 'b', 'b']
        # If empty, tokens is []
        tokens = list(string)
        data = {
            "grammar": self.grammar,
            "start_symbol": self.start_symbol,
            "input_tokens": tokens
        }
        return solve_universal("CFG Derivation", data)

    def test_aaabbb(self):
        result = self.run_cfg("aaabbb")
        html = result['subquestions'][0]['answer']
        
        # 1. Parsed grammar
        self.assertIn("S -&gt; 'a' S 'b'", html.replace("->", "-&gt;"))
        self.assertIn("S -&gt;", html.replace("->", "-&gt;")) # for the epsilon production
        
        # 2. Parse tree
        self.assertIn("mode_b_cfg_tree", html)
        self.assertIn("<img src=", html)
        
        # 3. Leftmost & Rightmost Derivation
        self.assertIn("<h4>Leftmost Derivation</h4>", html)
        self.assertIn("<h4>Rightmost Derivation</h4>", html)
        
        # Verify it hits 'a a a b b b' at the end (the epsilon vanishes)
        self.assertIn("&rArr; a a a b b b", html)
        
        # Verify it shows unambiguous (1 parse tree)
        self.assertIn("Only 1 parse tree was found", html)

    def test_other_strings(self):
        # Empty string: accepted
        res_empty = self.run_cfg("")
        self.assertIn("Only 1 parse tree was found", res_empty['subquestions'][0]['answer'])
        self.assertIn("&epsilon;", res_empty['subquestions'][0]['answer'])
        
        # ab: accepted
        res_ab = self.run_cfg("ab")
        self.assertIn("Only 1 parse tree was found", res_ab['subquestions'][0]['answer'])
        
        # aabb: accepted
        res_aabb = self.run_cfg("aabb")
        self.assertIn("Only 1 parse tree was found", res_aabb['subquestions'][0]['answer'])
        
        # aabbb: rejected
        res_aabbb = self.run_cfg("aabbb")
        self.assertIn("The string is not generated by the grammar", res_aabbb['subquestions'][0]['answer'])
        
        # ba: rejected
        res_ba = self.run_cfg("ba")
        self.assertIn("The string is not generated by the grammar", res_ba['subquestions'][0]['answer'])

if __name__ == '__main__':
    unittest.main()
