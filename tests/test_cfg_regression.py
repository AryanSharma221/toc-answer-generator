import unittest
from core.universal_generator import solve_universal
from solvers.cfg_solver import CFGSolver

class TestCFGRegression(unittest.TestCase):
    def setUp(self):
        # We will test using the actual solve_universal wrapper or the CFGSolver directly
        self.grammar_str = "S -> 'a' S 'b' | epsilon"
        self.start_sym = "S"

    def run_membership(self, string_tokens):
        data = {
            "grammar": self.grammar_str,
            "start_symbol": self.start_sym,
            "input_tokens": string_tokens,
            "derivation": "Leftmost"
        }
        res = solve_universal("CFG Derivation", data)
        html = res['subquestions'][0]['answer']
        # If it's accepted, the HTML will contain derivation arrows (&rArr;) or 'Parse Tree 1'
        # If rejected, it contains 'is not generated by the grammar' or 'Grammar does not cover'
        is_accepted = 'Parse Tree 1' in html
        return is_accepted, html

    def test_cfg_regression_strings(self):
        # Expected results as tuples: (string_tokens, expected_acceptance)
        test_cases = [
            ([], True), # Empty string
            (["a", "b"], True),
            (["a", "a", "b", "b"], True),
            (["a", "a", "a", "b", "b", "b"], True),
            (["a", "a", "b", "b", "b"], False),
            (["b", "a"], False),
            (["a", "a", "b"], False)
        ]
        
        for tokens, expected in test_cases:
            with self.subTest(tokens=tokens):
                accepted, html = self.run_membership(tokens)
                self.assertEqual(accepted, expected, f"Failed on tokens {tokens}")
                
                # Check specific derivation steps for aaabbb
                if tokens == ["a", "a", "a", "b", "b", "b"]:
                    self.assertIn("&rArr; S", html)
                    self.assertIn("&rArr; a S b", html)
                    self.assertIn("&rArr; a a S b b", html)
                    self.assertIn("&rArr; a a a S b b b", html)
                    self.assertIn("&rArr; a a a b b b", html)

    def test_malformed_grammar_regression(self):
        data = {
            "grammar": "S -> ", # Malformed
            "start_symbol": "S",
            "input_tokens": ["a"]
        }
        res = solve_universal("CFG Derivation", data)
        self.assertIn("Grammar does not cover some of the input words", res['subquestions'][0]['answer'])

    def test_undefined_symbol_regression(self):
        data = {
            "grammar": "S -> 'a' X 'b'", # X is undefined
            "start_symbol": "S",
            "input_tokens": ["a", "b"]
        }
        res = solve_universal("CFG Derivation", data)
        # NLTK just won't be able to generate the string because X goes nowhere
        self.assertIn("is not generated by the grammar", res['subquestions'][0]['answer'])

if __name__ == '__main__':
    unittest.main()
