import unittest
import json
from core.universal_generator import solve_universal

class TestUIScenarios(unittest.TestCase):
    
    def test_dfa_empty_json(self):
        # Malformed/empty input test
        with self.assertRaises(Exception):
            json.loads("")
            
    def test_dfa_missing_transitions(self):
        # Valid JSON but missing transitions
        data = {
            "states": ["A"],
            "alphabet": ["0"],
            "start_state": "A",
            "accepting_states": ["A"],
            "transitions": {},
            "strings": ["0"]
        }
        res = solve_universal("String Acceptance Traces", data)
        self.assertIn("no defined transitions", res['subquestions'][0]['answer'])
        
    def test_dfa_unknown_symbol(self):
        # Valid JSON but string contains symbol not in alphabet
        data = {
            "states": ["A"],
            "alphabet": ["0"],
            "start_state": "A",
            "accepting_states": ["A"],
            "transitions": {"A": {"0": "A"}},
            "strings": ["1"]
        }
        res = solve_universal("String Acceptance Traces", data)
        self.assertIn("Error - Symbol '1' not in alphabet", res['subquestions'][0]['answer'])
        
    def test_cfg_empty_grammar(self):
        # Empty grammar string should be caught by UI, but if passed down:
        data = {
            "grammar": "",
            "start_symbol": "S",
            "input_tokens": ["a"]
        }
        res = solve_universal("CFG Derivation", data)
        self.assertIn("No productions found", res['subquestions'][0]['answer'])
            
    def test_cfg_undefined_symbols(self):
        # Target string has token not generated by grammar
        data = {
            "grammar": "S -> 'a'",
            "start_symbol": "S",
            "input_tokens": ["b"]
        }
        res = solve_universal("CFG Derivation", data)
        self.assertIn("Grammar does not cover", res['subquestions'][0]['answer'])
        
    def test_dfa_valid_generation(self):
        data = {
            "states": ["q0", "q1"],
            "alphabet": ["0", "1"],
            "start_state": "q0",
            "accepting_states": ["q1"],
            "transitions": {"q0": {"0": "q1", "1": "q0"}, "q1": {"0": "q0", "1": "q1"}},
            "strings": ["0"]
        }
        res = solve_universal("String Acceptance Traces", data)
        # Should be accepted
        self.assertIn("Accepted", res['subquestions'][0]['answer'])
        self.assertNotIn("Error", res['subquestions'][0]['answer'])

if __name__ == '__main__':
    unittest.main()
