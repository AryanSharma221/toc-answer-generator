import unittest
from solvers.cfg_solver import CFGSolver
from core.universal_generator import solve_universal

class TestCFGTokenizationAndValidation(unittest.TestCase):
    def setUp(self):
        self.grammar = "S -> ( S ) S | epsilon"
        self.start_sym = "S"
        self.alphabet = "(, )"

    def run_solve(self, target_str):
        data = {
            "grammar": self.grammar,
            "start_symbol": self.start_sym,
            "alphabet": self.alphabet,
            "input_tokens": target_str,
            "derivation": "Leftmost"
        }
        return solve_universal("CFG Derivation", data)

    def test_space_separated_valid_1(self):
        # - ( ( ) ) ( ) -> Accepted; represents (())()
        target = "( ( ) ) ( )"
        solver = CFGSolver(self.grammar, self.start_sym, alphabet=self.alphabet)
        tokens = solver.tokenize_input(target)
        self.assertEqual(tokens, ["(", "(", ")", ")", "(", ")"])
        
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Accepted", ans)
        self.assertIn("(())()", ans)
        self.assertNotIn("outside the alphabet", ans)
        self.assertIn("mode_b_cfg_tree_0", ans)

    def test_space_separated_valid_2(self):
        # - ( ) -> Accepted; represents ()
        target = "( )"
        solver = CFGSolver(self.grammar, self.start_sym, alphabet=self.alphabet)
        tokens = solver.tokenize_input(target)
        self.assertEqual(tokens, ["(", ")"])
        
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Accepted", ans)
        self.assertIn("()", ans)
        self.assertIn("mode_b_cfg_tree_0", ans)

    def test_space_separated_valid_3(self):
        # - ( ( ( ) ) ) -> Accepted; represents ((()))
        target = "( ( ( ) ) )"
        solver = CFGSolver(self.grammar, self.start_sym, alphabet=self.alphabet)
        tokens = solver.tokenize_input(target)
        self.assertEqual(tokens, ["(", "(", "(", ")", ")", ")"])
        
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Accepted", ans)
        self.assertIn("((()))", ans)
        self.assertIn("mode_b_cfg_tree_0", ans)

    def test_unbalanced_parentheses_rejected(self):
        # - ( ( ) -> Rejected; unbalanced parentheses
        target = "( ( )"
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Rejected", ans)
        self.assertIn("The string is not generated by the grammar", ans)
        self.assertNotIn("mode_b_cfg_tree_0", ans)

    def test_symbol_outside_alphabet_rejected(self):
        # - ( x ) -> Rejected; x is outside the alphabet
        target = "( x )"
        solver = CFGSolver(self.grammar, self.start_sym, alphabet=self.alphabet)
        tokens = solver.tokenize_input(target)
        self.assertEqual(tokens, ["(", "x", ")"])
        err = solver.validate_tokens(tokens)
        self.assertIsNotNone(err)
        self.assertIn("outside the alphabet", err)
        
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Rejected", ans)
        self.assertIn("outside the alphabet", ans)
        self.assertNotIn("mode_b_cfg_tree_0", ans)

    def test_empty_target_accepted(self):
        # - Empty target -> Accepted because this grammar generates epsilon
        target = ""
        res = self.run_solve(target)
        ans = res['subquestions'][0]['answer']
        self.assertIn("Accepted", ans)
        self.assertIn("mode_b_cfg_tree_0", ans)

    def test_multichar_and_single_char_inputs(self):
        # Preserve support for ordinary single-char inputs like "a a b b"
        grammar_ab = "S -> a S b | epsilon"
        solver_ab = CFGSolver(grammar_ab, "S", alphabet="a, b")
        self.assertEqual(solver_ab.tokenize_input("a a b b"), ["a", "a", "b", "b"])
        self.assertEqual(solver_ab.tokenize_input("aabb"), ["a", "a", "b", "b"])

        # Preserve support for multichar terminals like "id + id"
        grammar_id = "E -> E '+' E | 'id'"
        solver_id = CFGSolver(grammar_id, "E", alphabet="id, +")
        self.assertEqual(solver_id.tokenize_input("id + id"), ["id", "+", "id"])

    def test_parser_boundary_no_spaces(self):
        """Asserts that the exact argument passed to the parsing library contains no separator-space terminals."""
        solver = CFGSolver(self.grammar, self.start_sym, alphabet=self.alphabet)
        passed_arguments = []
        original_parse = solver.parser.parse
        
        def spy_parse(sent):
            passed_arguments.append(sent)
            return original_parse(sent)
            
        solver.parser.parse = spy_parse
        
        # 1. Space-separated target "( ( ) ) ( )"
        solver.parse("( ( ) ) ( )")
        self.assertGreater(len(passed_arguments), 0)
        arg = passed_arguments[-1]
        if isinstance(arg, str):
            self.assertEqual(arg, "(())()")
            self.assertNotIn(" ", arg)
        else:
            self.assertEqual(arg, ["(", "(", ")", ")", "(", ")"])
            self.assertNotIn(" ", arg)
            
        # 2. Compact target "(())()" must normalize identically
        solver.parse("(())()")
        arg_compact = passed_arguments[-1]
        self.assertEqual(arg_compact, arg)
        
        # 3. Multi-character terminal grammar
        g_multi = "E -> E '+' E | 'id'"
        s_multi = CFGSolver(g_multi, "E", alphabet="id, +")
        multi_passed = []
        orig_multi_parse = s_multi.parser.parse
        s_multi.parser.parse = lambda sent: (multi_passed.append(sent), orig_multi_parse(sent))[1]
        
        s_multi.parse("id + id")
        self.assertEqual(multi_passed[-1], ["id", "+", "id"])
        self.assertNotIn(" ", multi_passed[-1])

    def test_compact_word_equivalences(self):
        # Test that ( ( ) ) ( ), (())() and ( ( ) ) ( ) normalize to the same result
        res_spaced = self.run_solve("( ( ) ) ( )")
        res_compact = self.run_solve("(())()")
        self.assertIn("Accepted", res_spaced['subquestions'][0]['answer'])
        self.assertIn("Accepted", res_compact['subquestions'][0]['answer'])
        self.assertIn("(())()", res_spaced['subquestions'][0]['answer'])
        self.assertIn("(())()", res_compact['subquestions'][0]['answer'])

if __name__ == '__main__':
    unittest.main()
